package backend

import (
	"fmt"
	"strings"
)

type CodeGenerator struct {
	IR       *IRProgram
	CSource  strings.Builder
	Includes []string
}

func NewCodeGenerator(ir *IRProgram) *CodeGenerator {
	cg := &CodeGenerator{
		IR:       ir,
		Includes: []string{"<stdio.h>", "<stdlib.h>", "<string.h>"},
	}
	return cg
}

func (cg *CodeGenerator) Generate() string {
	cg.CSource.Reset()

	cg.writeLine("// Generated by Skorpion Compiler")
	cg.writeLine("// Copyrights. (c) 2026 iamtowvee")
	cg.writeLine("")

	for _, inc := range cg.Includes {
		cg.writeLine(fmt.Sprintf("#include %s", inc))
	}

	cg.writeLine("")
	cg.writeLine("// Skorpion type definitions")
	cg.writeLine("typedef char* sk_string;")
	cg.writeLine("typedef int sk_bool;")
	cg.writeLine("#define true 1")
	cg.writeLine("#define false 0")
	cg.writeLine("")

	cg.writeLine("// Skorpion any type")
	cg.writeLine("typedef struct {")
	cg.writeLine("    int type;")
	cg.writeLine("    union {")
	cg.writeLine("        int i;")
	cg.writeLine("        float f;")
	cg.writeLine("        double d;")
	cg.writeLine("        sk_string s;")
	cg.writeLine("        sk_bool b;")
	cg.writeLine("        void* p;")
	cg.writeLine("    } data;")
	cg.writeLine("} sk_any;")
	cg.writeLine("")

	cg.writeLine("// Any constructors")
	cg.writeLine("sk_any any_int(int v) { sk_any a; a.type=0; a.data.i=v; return a; }")
	cg.writeLine("sk_any any_string(sk_string v) { sk_any a; a.type=1; a.data.s=v; return a; }")
	cg.writeLine("sk_any any_float(float v) { sk_any a; a.type=2; a.data.f=v; return a; }")
	cg.writeLine("sk_any any_double(double v) { sk_any a; a.type=3; a.data.d=v; return a; }")
	cg.writeLine("sk_any any_bool(sk_bool v) { sk_any a; a.type=4; a.data.b=v; return a; }")
	cg.writeLine("sk_any any_ptr(void* v) { sk_any a; a.type=5; a.data.p=v; return a; }")
	cg.writeLine("")

	cg.writeLine("// Any getters")
	cg.writeLine("int any_get_int(sk_any a) { return a.data.i; }")
	cg.writeLine("sk_string any_get_string(sk_any a) { return a.data.s; }")
	cg.writeLine("float any_get_float(sk_any a) { return a.data.f; }")
	cg.writeLine("double any_get_double(sk_any a) { return a.data.d; }")
	cg.writeLine("sk_bool any_get_bool(sk_any a) { return a.data.b; }")
	cg.writeLine("void* any_get_ptr(sk_any a) { return a.data.p; }")
	cg.writeLine("")

	cg.writeLine("// Any to string")
	cg.writeLine("sk_string any_to_string(sk_any a) {")
	cg.writeLine("    char buf[64];")
	cg.writeLine("    switch (a.type) {")
	cg.writeLine("        case 0: snprintf(buf, 64, \"%d\", a.data.i); return strdup(buf);")
	cg.writeLine("        case 1: return strdup(a.data.s);")
	cg.writeLine("        case 2: snprintf(buf, 64, \"%f\", a.data.f); return strdup(buf);")
	cg.writeLine("        case 3: snprintf(buf, 64, \"%f\", a.data.d); return strdup(buf);")
	cg.writeLine("        case 4: return strdup(a.data.b ? \"true\" : \"false\");")
	cg.writeLine("        case 5: snprintf(buf, 64, \"%p\", a.data.p); return strdup(buf);")
	cg.writeLine("        default: return strdup(\"unknown\");")
	cg.writeLine("    }")
	cg.writeLine("}")
	cg.writeLine("")

	cg.writeLine("// Function prototypes")
	for _, fn := range cg.IR.Functions {
		if fn.Name == "main" {
			continue
		}
		returnType := cg.typeToC(fn.ReturnType)
		params := []string{}
		for _, p := range fn.Params {
			params = append(params, fmt.Sprintf("%s %s", cg.typeToC(p.Type), p.Name))
		}
		paramsStr := strings.Join(params, ", ")
		if paramsStr == "" {
			paramsStr = "void"
		}
		cg.writeLine(fmt.Sprintf("%s %s(%s);", returnType, fn.Name, paramsStr))
	}
	cg.writeLine("")

	if cg.IR.InlineC != "" {
		cg.writeLine("// Inline C code")
		cg.writeLine(cg.IR.InlineC)
		cg.writeLine("")
	}

	if len(cg.IR.Globals) > 0 {
		cg.writeLine("// Global variables")
		for _, g := range cg.IR.Globals {
			qualifier := ""
			if g.IsConst {
				qualifier = "const "
			}
			cg.writeLine(fmt.Sprintf("%s%s %s = %s;", qualifier, cg.typeToC(g.Type), g.Name, g.Value))
		}
		cg.writeLine("")
	}

	for _, fn := range cg.IR.Functions {
		cg.generateFunction(&fn)
	}

	return cg.CSource.String()
}

func (cg *CodeGenerator) generateFunction(fn *IRFunction) {
	returnType := cg.typeToC(fn.ReturnType)

	params := []string{}
	for _, p := range fn.Params {
		params = append(params, fmt.Sprintf("%s %s", cg.typeToC(p.Type), p.Name))
	}
	paramsStr := strings.Join(params, ", ")
	if paramsStr == "" {
		paramsStr = "void"
	}

	cg.writeLine(fmt.Sprintf("%s %s(%s) {", returnType, fn.Name, paramsStr))

	if len(fn.Locals) > 0 {
		for _, local := range fn.Locals {
			cg.writeLine(fmt.Sprintf("    %s;", local))
		}
		cg.writeLine("")
	}

	for _, ins := range fn.Instructions {
		cg.generateInstruction(&ins, fn)
	}

	if fn.ReturnType == "void" && len(fn.Instructions) > 0 {
		lastIns := fn.Instructions[len(fn.Instructions)-1]
		if lastIns.Op != "ret" {
			cg.writeLine("    return;")
		}
	}

	cg.writeLine("}")
	cg.writeLine("")
}

func (cg *CodeGenerator) generateInstruction(ins *IRInstruction, fn *IRFunction) {
	indent := "    "

	switch ins.Op {
	case "label":
		cg.writeLine(fmt.Sprintf("%s:", ins.Result))

	case "free":
		cg.writeLine(fmt.Sprintf("%sfree(%s);", indent, ins.Arg1))

	case "inline_c":
		lines := strings.Split(ins.Arg1, "\n")
		for _, line := range lines {
			if strings.TrimSpace(line) != "" {
				cg.writeLine(fmt.Sprintf("%s%s", indent, line))
			}
		}

	case "typeof_any":
		cg.writeLine(fmt.Sprintf("%ssk_string %s;", indent, ins.Result))
		cg.writeLine(fmt.Sprintf("%schar buf[32];", indent))
		cg.writeLine(fmt.Sprintf("%sswitch (%s.type) {", indent, ins.Arg1))
		cg.writeLine(fmt.Sprintf("%s    case 0: strcpy(buf, \"int\"); break;", indent))
		cg.writeLine(fmt.Sprintf("%s    case 1: strcpy(buf, \"string\"); break;", indent))
		cg.writeLine(fmt.Sprintf("%s    case 2: strcpy(buf, \"float\"); break;", indent))
		cg.writeLine(fmt.Sprintf("%s    case 3: strcpy(buf, \"double\"); break;", indent))
		cg.writeLine(fmt.Sprintf("%s    case 4: strcpy(buf, \"bool\"); break;", indent))
		cg.writeLine(fmt.Sprintf("%s    case 5: strcpy(buf, \"ptr\"); break;", indent))
		cg.writeLine(fmt.Sprintf("%s    default: strcpy(buf, \"unknown\"); break;", indent))
		cg.writeLine(fmt.Sprintf("%s}", indent))
		cg.writeLine(fmt.Sprintf("%s%s = strdup(buf);", indent, ins.Result))

	case "comment":
		cg.writeLine(fmt.Sprintf("%s// %s", indent, ins.Arg1))

	case "strcat":
		cg.writeLine(fmt.Sprintf("%schar %s[256];", indent, ins.Result))
		cg.writeLine(fmt.Sprintf("%sstrcpy(%s, %s);", indent, ins.Result, ins.Arg1))
		cg.writeLine(fmt.Sprintf("%sstrcat(%s, %s);", indent, ins.Result, ins.Arg2))

	case "to_string":
		// Проверяем, является ли аргумент any
		isAny := false
		for _, local := range fn.Locals {
			if strings.Contains(local, ins.Arg1) && strings.Contains(local, "sk_any") {
				isAny = true
				break
			}
		}
		if !isAny {
			for _, param := range fn.Params {
				if param.Name == ins.Arg1 && param.Type == "any" {
					isAny = true
					break
				}
			}
		}
		if isAny {
			cg.writeLine(fmt.Sprintf("%ssk_string %s = any_to_string(%s);", indent, ins.Result, ins.Arg1))
		} else {
			cg.writeLine(fmt.Sprintf("%schar %s[32];", indent, ins.Result))
			cg.writeLine(fmt.Sprintf("%ssnprintf(%s, 32, \"%%d\", %s);", indent, ins.Result, ins.Arg1))
		}

	case "$":
		// Проверяем, является ли аргумент any
		isAny := false
		for _, local := range fn.Locals {
			if strings.Contains(local, ins.Arg1) && strings.Contains(local, "sk_any") {
				isAny = true
				break
			}
		}
		if !isAny {
			for _, param := range fn.Params {
				if param.Name == ins.Arg1 && param.Type == "any" {
					isAny = true
					break
				}
			}
		}
		if isAny {
			cg.writeLine(fmt.Sprintf("%ssk_string %s = any_to_string(%s);", indent, ins.Result, ins.Arg1))
		} else {
			cg.writeLine(fmt.Sprintf("%schar %s[32];", indent, ins.Result))
			cg.writeLine(fmt.Sprintf("%ssnprintf(%s, 32, \"%%d\", %s);", indent, ins.Result, ins.Arg1))
		}

	case "ret":
		if ins.Arg1 != "" {
			cg.writeLine(fmt.Sprintf("%sreturn %s;", indent, ins.Arg1))
		} else {
			cg.writeLine(fmt.Sprintf("%sreturn;", indent))
		}

	case "call":
		if ins.Result != "" {
			returnType := ins.ReturnType
			if returnType == "" {
				returnType = "sk_string"
			}

			if returnType == "void" {
				cg.writeLine(fmt.Sprintf("%s%s(%s);", indent, ins.Arg1, ins.Arg2))
				if strings.HasPrefix(ins.Result, "t") {
					cg.writeLine(fmt.Sprintf("%sint %s = 0;", indent, ins.Result))
				}
			} else {
				if strings.HasPrefix(ins.Result, "t") {
					cg.writeLine(fmt.Sprintf("%s%s %s = %s(%s);", indent, returnType, ins.Result, ins.Arg1, ins.Arg2))
				} else {
					cg.writeLine(fmt.Sprintf("%s%s = %s(%s);", indent, ins.Result, ins.Arg1, ins.Arg2))
				}
			}
		} else {
			cg.writeLine(fmt.Sprintf("%s%s(%s);", indent, ins.Arg1, ins.Arg2))
		}

	case "if":
		cg.writeLine(fmt.Sprintf("%sif %s {", indent, ins.Result))
		cg.writeLine(fmt.Sprintf("%s    goto %s;", indent, ins.Arg1))
		cg.writeLine(fmt.Sprintf("%s} else {", indent))
		cg.writeLine(fmt.Sprintf("%s    goto %s;", indent, ins.Arg2))
		cg.writeLine(fmt.Sprintf("%s}", indent))

	case "goto":
		cg.writeLine(fmt.Sprintf("%sgoto %s;", indent, ins.Result))

	case "=":
		if strings.HasPrefix(ins.Result, "t") {
			argType := "int"
			if strings.HasPrefix(ins.Arg1, "\"") && strings.HasSuffix(ins.Arg1, "\"") {
				argType = "sk_string"
			} else if strings.Contains(ins.Arg1, ".") {
				argType = "double"
			} else if ins.Arg1 == "true" || ins.Arg1 == "false" {
				argType = "sk_bool"
			}
			cg.writeLine(fmt.Sprintf("%s%s %s = %s;", indent, argType, ins.Result, ins.Arg1))
		} else {
			cg.writeLine(fmt.Sprintf("%s%s = %s;", indent, ins.Result, ins.Arg1))
		}

	case "+", "-", "*", "/":
		if strings.HasPrefix(ins.Result, "t") {
			cg.writeLine(fmt.Sprintf("%sint %s = %s %s %s;", indent, ins.Result, ins.Arg1, ins.Op, ins.Arg2))
		} else {
			cg.writeLine(fmt.Sprintf("%s%s = %s %s %s;", indent, ins.Result, ins.Arg1, ins.Op, ins.Arg2))
		}

	default:
		if ins.Result != "" && ins.Arg1 != "" && ins.Arg2 != "" {
			cg.writeLine(fmt.Sprintf("%s%s %s %s %s;", indent, ins.Result, ins.Op, ins.Arg1, ins.Arg2))
		} else if ins.Result != "" && ins.Arg1 != "" {
			cg.writeLine(fmt.Sprintf("%s%s %s %s;", indent, ins.Result, ins.Op, ins.Arg1))
		} else {
			cg.writeLine(fmt.Sprintf("%s%s;", indent, ins.Result))
		}
	}
}

func (cg *CodeGenerator) typeToC(typ string) string {
	switch typ {
	case "int":
		return "int"
	case "string":
		return "sk_string"
	case "float":
		return "float"
	case "double":
		return "double"
	case "bool":
		return "sk_bool"
	case "char":
		return "char"
	case "void":
		return "void"
	case "arr":
		return "void*"
	case "dict":
		return "void*"
	case "any":
		return "sk_any"
	default:
		return "int"
	}
}

func (cg *CodeGenerator) writeLine(line string) {
	cg.CSource.WriteString(line + "\n")
}
