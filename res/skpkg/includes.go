package skpkg

import (
	"bytes"
	"fmt"
	"io"
	"path"
	"strings"

	"gopkg.in/yaml.v3"
)

const IncludesFormatVersion = 1

type LibraryRef struct {
	File    string `yaml:"file"`
	Hash    string `yaml:"hash"`
	Name    string `yaml:"name"`
	Version string `yaml:"version"`
	Author  string `yaml:"author"`
}

type IncludeEntry struct {
	Hash   string `yaml:"hash"`
	Out    string `yaml:"out"`
	Size   int64  `yaml:"size"`
	Source string `yaml:"source,omitempty"`
}

// CCFlagsConfig — флаги компилятора для каждой ОС.
type CCFlagsConfig struct {
	Linux   []string `yaml:"linux,omitempty"`
	Windows []string `yaml:"windows,omitempty"`
	Darwin  []string `yaml:"darwin,omitempty"`
}

type Includes struct {
	FormatVersion int            `yaml:"formatVersion"`
	Library       LibraryRef     `yaml:"library"`
	Includes      []IncludeEntry `yaml:"includes"`
	CCFlags       CCFlagsConfig  `yaml:"ccflags,omitempty"`
}

func EncodeIncludes(m *Includes) ([]byte, error) {
	if err := m.Validate(); err != nil {
		return nil, err
	}
	body, err := yaml.Marshal(m)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	buf.WriteString("# Generated by Skorpion. Part of a .skpkg archive — do not edit.\n")
	buf.Write(body)
	return buf.Bytes(), nil
}

func DecodeIncludes(data []byte) (*Includes, error) {
	if int64(len(data)) > maxIncludesSize {
		return nil, fmt.Errorf("%s is too large (%d bytes)", includesFileName, len(data))
	}

	dec := yaml.NewDecoder(bytes.NewReader(data))
	dec.KnownFields(true)

	var m Includes
	if err := dec.Decode(&m); err != nil {
		return nil, fmt.Errorf("cannot parse %s: %w", includesFileName, err)
	}

	var extra Includes
	if err := dec.Decode(&extra); err != io.EOF {
		if err == nil {
			return nil, fmt.Errorf("%s: multiple YAML documents are not allowed", includesFileName)
		}
		return nil, fmt.Errorf("cannot parse %s: %w", includesFileName, err)
	}

	if err := m.Validate(); err != nil {
		return nil, err
	}
	return &m, nil
}

func (m *Includes) Validate() error {
	if m.FormatVersion != IncludesFormatVersion {
		return fmt.Errorf("unsupported %s format version %d (expected %d)",
			includesFileName, m.FormatVersion, IncludesFormatVersion)
	}

	if m.Library.File == "" || path.Base(m.Library.File) != m.Library.File ||
		!strings.HasSuffix(m.Library.File, libraryExt) {
		return fmt.Errorf("library.file must be a '%s' file name without directories, got '%s'",
			libraryExt, m.Library.File)
	}
	if err := CheckRelativePath(m.Library.File); err != nil {
		return fmt.Errorf("library.file: %w", err)
	}
	if !IsHash(m.Library.Hash) {
		return fmt.Errorf("library.hash must be a 64-character lowercase sha256, got '%s'", m.Library.Hash)
	}
	for _, id := range []struct{ label, value string }{
		{"library.name", m.Library.Name},
		{"library.version", m.Library.Version},
		{"library.author", m.Library.Author},
	} {
		if err := CheckIdentifier(id.value); err != nil {
			return fmt.Errorf("%s: %w", id.label, err)
		}
	}

	if len(m.Includes) > maxPackageEntries {
		return fmt.Errorf("too many entries in %s: %d (limit %d)",
			includesFileName, len(m.Includes), maxPackageEntries)
	}

	seenOut := make(map[string]string, len(m.Includes))
	for i, e := range m.Includes {
		if !IsHash(e.Hash) {
			return fmt.Errorf("includes[%d]: hash must be a 64-character lowercase sha256, got '%s'", i, e.Hash)
		}
		if e.Size < 0 || e.Size > maxIncludeFileSize {
			return fmt.Errorf("includes[%d]: invalid size %d (limit %d)", i, e.Size, maxIncludeFileSize)
		}
		if strings.HasSuffix(e.Out, "/") {
			return fmt.Errorf("includes[%d]: out '%s' must be a file path, not a directory", i, e.Out)
		}
		if err := ValidateOutPattern(e.Out); err != nil {
			return fmt.Errorf("includes[%d]: %w", i, err)
		}
		key := strings.ToLower(e.Out)
		if prev, ok := seenOut[key]; ok {
			return fmt.Errorf("includes[%d]: destination '%s' conflicts with '%s'", i, e.Out, prev)
		}
		seenOut[key] = e.Out

		if e.Source != "" {
			if err := CheckRelativePath(e.Source); err != nil {
				return fmt.Errorf("includes[%d]: source: %w", i, err)
			}
		}
	}
	return nil
}
